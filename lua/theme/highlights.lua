-- ── helper: make a hl entry ──────────────────────────────────────────────────
local function hl(fg, bg, opts)
  local t = {}
  if fg then
    t.fg = fg
  end
  if bg then
    t.bg = bg
  end
  if opts then
    for k, v in pairs(opts) do
      t[k] = v
    end
  end
  return t
end

